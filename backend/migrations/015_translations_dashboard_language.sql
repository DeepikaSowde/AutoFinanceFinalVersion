-- 015: English → Tamil UI text and each user's Dashboard language.
--
-- translations holds MotoLend-English-to-Tamil.xlsx as approved: one row per
-- English text per workbook sheet (sheets can give the same English a
-- different Tamil, so the sheet is part of the key). It is shared by every
-- lender. The seed below matches frontend/src/i18n/motolendTamil.js, which
-- the app falls back to when the API cannot be reached.
--
-- users.dashboard_language is the English | தமிழ் choice on the Dashboard,
-- kept on the account so it follows the user to any device.

CREATE TABLE IF NOT EXISTS translations (
  sheet       TEXT NOT NULL,
  english     TEXT NOT NULL,
  tamil       TEXT NOT NULL,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (sheet, english)
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS dashboard_language TEXT NOT NULL DEFAULT 'en';
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_dashboard_language_check;
ALTER TABLE users ADD CONSTRAINT users_dashboard_language_check CHECK (dashboard_language IN ('en', 'ta'));

